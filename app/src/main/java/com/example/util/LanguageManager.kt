    fun getString(key: String): String {
        val langCode = currentLanguage.code
        val langMap = translations[langCode] ?: translations["zh-CN"] ?: translations["en"]
        return langMap?.get(key)
            ?: translations["zh-CN"]?.get(key)
            ?: translations["en"]?.get(key)
            ?: key
    }
}

/**
 * Convenience Compose function to look up translated string reactively.
 */
@Composable
fun appString(key: String): String {
    // Reading currentLanguage triggers recomposition whenever language changes
    val current = LanguageManager.currentLanguage
    return LanguageManager.getString(key)
}
